export function stableVisualBytes(cache: Map<string, { bytes: number; ts: number }>, rawBytes: number, key: string): number {
  const now = Date.now()
  const cached = cache.get(key)
  if (!cached) {
    cache.set(key, { bytes: rawBytes, ts: now })
    return rawBytes
  }
  const ratio = rawBytes / (cached.bytes || 1)
  if (ratio > 1.3 || ratio < 1 / 1.3 || now - cached.ts > 30000) {
    cache.set(key, { bytes: rawBytes, ts: now })
    return rawBytes
  }
  return cached.bytes
}

export interface CountryTotal {
  country: string
  bytes: number
  packets: number
  ipCount: number
  topIP: string
  topIPOrg: string
  topIPBytes: number
}

export function aggregateByCountry(points: GeoPoint[] | undefined): CountryTotal[] {
  const totals: Record<string, CountryTotal> = {}
  const order: string[] = []
  ;(points || []).forEach((p) => {
    if (!p.country) return
    let t = totals[p.country]
    if (!t) {
      t = { country: p.country, bytes: 0, packets: 0, ipCount: 0, topIP: p.ip, topIPOrg: p.org || '', topIPBytes: 0 }
      totals[p.country] = t
      order.push(p.country)
    }
    t.bytes += p.bytes
    t.packets += p.packets
    t.ipCount += 1
    if (p.bytes > t.topIPBytes) {
      t.topIPBytes = p.bytes
      t.topIP = p.ip
      t.topIPOrg = p.org || ''
    }
  })
  return order.map((c) => totals[c]).sort((a, b) => b.bytes - a.bytes)
}
